"use client";

import type { FormEvent } from "react";
import { useEffect, useId, useRef, useState } from "react";
import type { FunctionReturnType } from "convex/server";
import { Laptop, Link2 } from "lucide-react";
import Link from "next/link";
import { z } from "zod";
import { Button } from "@companynerve/ui";
import type { api } from "../../../convex/_generated/api";
import { AccountSection, AccountStatus } from "./account-layout";

type Device = FunctionReturnType<typeof api.devices.list>[number];
const hash = z.string().regex(/^[a-f0-9]{64}$/);
const publicRequest = z.strictObject({
  codeHash: hash,
  credentialHash: hash,
  fingerprint: hash,
  name: z.string().max(80),
  workspaceId: z.string(),
});

export function AccountComputers({
  organizationId,
  devices,
  canPair,
  canRevoke,
  busy,
  call,
}: {
  organizationId: string;
  devices: Device[];
  canPair: boolean;
  canRevoke: boolean;
  busy: boolean;
  call: (operation: string, args: unknown) => Promise<unknown>;
}) {
  const id = useId();
  const [pairing, setPairing] = useState<{
    id: string;
    name: string;
    fingerprint: string;
    credentialHash: string;
  } | null>(null);
  const [error, setError] = useState("");
  const requestField = useRef<HTMLTextAreaElement>(null);
  const devicesHeading = useRef<HTMLHeadingElement>(null);
  const confirmationHeading = useRef<HTMLHeadingElement>(null);
  const requestPending = useRef(false);
  const returnToRequest = useRef(false);

  useEffect(() => {
    if (pairing) {
      confirmationHeading.current?.focus({ preventScroll: true });
      confirmationHeading.current?.parentElement?.scrollIntoView({
        block: "nearest",
      });
    } else if (returnToRequest.current) {
      returnToRequest.current = false;
      requestField.current?.focus();
    }
  }, [pairing]);

  async function reviewRequest(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!canPair || busy || requestPending.current) return;
    setError("");
    setPairing(null);
    const raw = new FormData(event.currentTarget).get("request");
    let parsed: z.infer<typeof publicRequest>;
    try {
      parsed = publicRequest.parse(JSON.parse(String(raw ?? "")));
    } catch {
      setError("Paste the public pairing request generated by your runner.");
      requestField.current?.focus();
      return;
    }
    if (parsed.workspaceId !== organizationId) {
      setError("This request belongs to a different workspace.");
      requestField.current?.focus();
      return;
    }
    const existing = devices.find(
      (device) =>
        device.personalOwned &&
        device.pairingActive &&
        device.fingerprint === parsed.fingerprint &&
        device.name === parsed.name,
    );
    requestPending.current = true;
    try {
      const deviceId =
        existing?._id ??
        (await call("startDevice", {
          organizationId,
          name: parsed.name,
          fingerprint: parsed.fingerprint,
          codeHash: parsed.codeHash,
        }));
      if (typeof deviceId !== "string") return;
      setPairing({
        id: deviceId,
        name: parsed.name,
        fingerprint: parsed.fingerprint,
        credentialHash: parsed.credentialHash,
      });
    } finally {
      requestPending.current = false;
    }
  }

  return (
    <div className="account-content">
      <div
        className={
          canPair ? "account-grid account-grid-start" : "account-content"
        }
      >
        <AccountSection
          title="Paired computers"
          headingRef={devicesHeading}
          description="Use a computer you control for approved local tasks."
          icon={Laptop}
        >
          {devices.length ? (
            <ul className="account-record-list">
              {devices.map((device) => (
                <li key={device._id}>
                  <div>
                    <strong>{device.name}</strong>
                    <p className="fine code-label">
                      Fingerprint {device.fingerprint}
                    </p>
                  </div>
                  <div className="account-actions">
                    <AccountStatus
                      tone={device.personalOnline ? "positive" : "neutral"}
                    >
                      {device.personalOnline ? "Online" : device.state}
                    </AccountStatus>
                    {canRevoke && device.state !== "revoked" && (
                      <Button
                        type="button"
                        variant="outline"
                        disabled={busy}
                        onClick={() =>
                          void call("revokeDevice", { id: device._id })
                        }
                      >
                        Revoke access
                      </Button>
                    )}
                  </div>
                </li>
              ))}
            </ul>
          ) : (
            <p>No paired computers to show.</p>
          )}
          <Link
            className="button secondary"
            href="/help/connect-your-computer"
            prefetch={false}
          >
            Runner setup guide
          </Link>
        </AccountSection>
        {canPair && (
          <AccountSection
            title="Pair a computer"
            icon={Link2}
            description={
              pairing
                ? undefined
                : "Run the setup guide’s pairing command, then paste the public request here."
            }
          >
            <form
              className="form-grid account-pairing-form"
              onSubmit={reviewRequest}
              aria-busy={busy}
              hidden={Boolean(pairing)}
            >
              <label htmlFor={`${id}-request`}>Public pairing request</label>
              <textarea
                ref={requestField}
                id={`${id}-request`}
                name="request"
                disabled={busy}
                required
                rows={5}
                maxLength={1200}
                spellCheck={false}
                aria-invalid={Boolean(error)}
                aria-describedby={error ? `${id}-error` : undefined}
                onChange={() => {
                  setError("");
                  if (pairing) setPairing(null);
                }}
              />
              {error && (
                <p id={`${id}-error`} role="alert" className="error">
                  {error}
                </p>
              )}
              <div className="account-actions">
                <Button type="submit" variant="outline" disabled={busy}>
                  {busy ? "Working…" : "Review device request"}
                </Button>
              </div>
            </form>
            {pairing && (
              <section className="account-pairing-confirm">
                <h3 ref={confirmationHeading} tabIndex={-1}>
                  Confirm {pairing.name}
                </h3>
                <p>
                  Compare this fingerprint with the one shown on your computer
                  before you confirm.
                </p>
                <code>{pairing.fingerprint}</code>
                <div className="account-actions">
                  <Button
                    type="button"
                    disabled={busy}
                    onClick={async () => {
                      if (requestPending.current) return;
                      requestPending.current = true;
                      try {
                        const result = await call("approveDevice", {
                          id: pairing.id,
                          fingerprint: pairing.fingerprint,
                          credentialHash: pairing.credentialHash,
                        });
                        if (result !== undefined) {
                          requestField.current?.form?.reset();
                          setPairing(null);
                          devicesHeading.current?.focus();
                        }
                      } finally {
                        requestPending.current = false;
                      }
                    }}
                  >
                    Confirm matching computer
                  </Button>
                  <Button
                    type="button"
                    variant="ghost"
                    disabled={busy}
                    onClick={() => {
                      returnToRequest.current = true;
                      setPairing(null);
                    }}
                  >
                    Cancel
                  </Button>
                </div>
              </section>
            )}
          </AccountSection>
        )}
      </div>
      <details className="account-disclosure">
        <summary>Local task requirements</summary>
        <p>
          Codex authentication stays on the paired computer. Runner setup
          includes repository mapping and isolation checks. Execution requires
          verified isolation and an approved plan.
        </p>
      </details>
    </div>
  );
}
