import { build } from "vite";
import tailwindcss from "@tailwindcss/vite";
import { viteSingleFile } from "vite-plugin-singlefile";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const resources = {};
for (const [name, entry] of [
  ["workspace", "index.html"],
  ["card", "card.html"],
  ["export", "export.html"],
]) {
  const outDir = resolve(root, "dist", name);
  await build({
    root,
    configFile: false,
    logLevel: "warn",
    plugins: [tailwindcss(), viteSingleFile()],
    build: {
      outDir,
      emptyOutDir: true,
      sourcemap: false,
      minify: true,
      rollupOptions: { input: resolve(root, entry) },
    },
  });
  const html = await readFile(resolve(outDir, entry), "utf8");
  if (
    html.includes("Sample personal workspace") ||
    html.includes("demo-private-workspace")
  )
    throw new Error("Development fixture entered the production widget.");
  if (html.length > 2500000)
    throw new Error(`${name} exceeds the 2.5 MB uncompressed resource ceiling`);
  resources[name] = html;
  console.log(
    `${name}: ${Buffer.byteLength(html)} bytes; ${gzipSync(html).length} gzip bytes`,
  );
}
const target = resolve(root, "../../packages/widget/resources.generated.ts");
await mkdir(dirname(target), { recursive: true });
await writeFile(
  target,
  `// Generated by apps/widget/scripts/build.mjs. No customer data or runtime credentials.\nexport const widgetResources = ${JSON.stringify(resources)} as const;\n`,
);
